package com.keuney.music.data.network

/**
 * 네트워크 대기 정책을 한곳에 모은다(ADR-040).
 *
 * 요청은 두 종류이며 성격이 달라 값을 따로 둔다.
 * - 메타데이터 요청(검색, 스트림 주소 해석)은 짧게 끝나야 한다. 오래 걸리면 사용자가 기다리는 화면이 멈춘다.
 * - 재생 요청은 큰 파일을 이어 받는다. 첫 바이트가 늦게 오는 일이 있어 조금 더 기다린다.
 *
 * 모든 값은 상한이며, 취소가 오면 값과 무관하게 즉시 중단한다.
 */
internal object NetworkTimeouts {
    /** 연결 수립까지 기다리는 시간. 두 종류가 같다. */
    const val CONNECT_MS = 10_000

    /** 메타데이터 요청에서 다음 바이트를 기다리는 시간. */
    const val SOURCE_SOCKET_MS = 20_000

    /** 메타데이터 요청 전체의 상한. 재시도까지 포함해 사용자가 기다리는 최대 시간을 정한다. */
    const val SOURCE_REQUEST_MS = 30_000

    /**
     * 재생 요청에서 다음 바이트를 기다리는 시간. media3 기본값은 8초로,
     * 공급자가 전송을 늦게 시작하면 재생이 곧바로 끊긴다. 실기기에서 관찰한 지연을 반영해 늘렸다.
     */
    const val PLAYBACK_READ_MS = 20_000
}
